/** Does the router's call (no environment class, so prod) go through a plan? */
export function viaPlan(model: ActionModel): boolean {
  return (
    model.mutating &&
    (model.planning === 'required' ||
      model.risk === 'high' ||
      model.risk === 'critical')
  );
}

export function httpSpecFile(model: ActionModel): string {
  const { http } = model;
  if (http === undefined) {
    throw new Error('an action without --http has no HTTP spec');
  }
  const connection = connectionParam(model);
  const planned = viaPlan(model);
  const job = model.kind === 'job';
  const url = http.path.replace(/\{([^{}]*)\}/g, (_match, name: string) =>
    encodeURIComponent(
      model.params.find((param) => param.name === name)?.sample ?? '',
    ),
  );
  const get = http.method === 'GET';
  const key = model.mutating ? ", headers: { 'idempotency-key': KEY }" : '';
  const request = `{ method: ${quote(http.method)}, path: ${quote(url)}${get ? '' : ', payload: {}'}${key} }`;
  const unexpected = get
    ? `{ method: 'GET', path: ${quote(`${url}?unexpected=1`)} }`
    : `{ method: ${quote(http.method)}, path: ${quote(url)}, payload: { unexpected: true }${key} }`;
  // The router sends no environment class, so every call is prod (OQ-283) and a mutation is
  // locked until a person arms the connection; a query is never locked.
  const arm =
    connection === undefined || !model.mutating
      ? ''
      : `    engine.arm(${quote(connection.sample)});\n`;
  const shape = `    if (done.kind !== 'output') throw new Error(\`expected output, got \${done.kind}\`);
    expect(def.output.safeParse(done.output).success).toBe(true);`;
  const answer = planned
    ? `    expect(answer.statusCode).toBe(428);
    expect(answer.json()).toMatchObject({ code: 'PLAN_REQUIRED' });
    const planId = /\\/plans\\/([^/]+)$/.exec(String(answer.headers.location))?.[1];
    if (planId === undefined) throw new Error('the 428 names no plan');
    const plan = await engine.executor.getPlan(planId as PlanId, engine.context());
    const done = await engine.executor.execute(
      {
        planId: plan.id,
        consents: [...plan.consentsRequired],
        confirmation: plan.confirmationPhrase,
        idempotencyKey: KEY,
      },
      engine.context(),
    );
${job ? "    expect(done.kind).toBe('job');" : `    expect(done.kind).toBe('output');\n${shape}`}`
    : job
      ? `    expect(answer.statusCode).toBe(202);
    expect(answer.json()).toHaveProperty('jobId');`
      : `    expect(answer.statusCode).toBe(200);
    expect(def.output.safeParse(answer.json()).success).toBe(true);`;
  const usesDef = !job;
  const contractNames = [
    ...(usesDef ? [model.camel] : []),
    ...(planned ? ['type PlanId'] : []),
  ];
  const contractImport =
    contractNames.length === 0
      ? ''
      : `import { ${contractNames.join(', ')} } from '@app/contracts';\n`;
  return `// Generated by \`pnpm nx g @app/generators:action ${model.id}\`. Requests go through the real router
// with createTestEngine().inject. They fail until create${model.pascal}Action is implemented; do not weaken them.
${contractImport}import { createRoleAuthorizer } from '@app/kernel';
import { create${model.pascal}Action, create${model.modulePascal}FakeDeps } from '@app/${model.module}';
import { afterEach, describe, expect, it } from 'vitest';

import { createTestEngine, type TestEngine } from '../create-test-engine.ts';

const subject = () =>
  create${model.pascal}Action(create${model.modulePascal}FakeDeps());
${usesDef ? `const def = ${model.camel};\n` : ''}${model.mutating ? "const KEY = 'generated-spec-key-0001';\n" : ''}let engine: TestEngine;

afterEach(async () => {
  await engine.close();
});

describe(${quote(`${http.method} ${http.path}`)}, () => {
  it('AC-1 the route runs ${model.id} and answers in the shape of the contract', async () => {
    engine = createTestEngine({ actions: [subject()] });
${arm}    const answer = await engine.inject(${request});

${answer}
  });

  it('AC-2 a request without the launch token is refused and nothing runs', async () => {
    engine = createTestEngine({ actions: [subject()] });

    const answer = await engine.inject({
      method: ${quote(http.method)},
      path: ${quote(url)},
      authenticated: false,
    });

    expect(answer.statusCode).toBe(401);
    expect(engine.audit.attempts).toEqual([]);
  });

  it('AC-3 a caller that does not hold ${model.permission} gets 403 and nothing runs', async () => {
    engine = createTestEngine({
      actions: [subject()],
      authorizer: createRoleAuthorizer({}),
    });
${arm}    const answer = await engine.inject(${request});

    expect(answer.statusCode).toBe(403);
    expect(answer.json()).toMatchObject({ code: 'FORBIDDEN_RBAC' });
    expect(engine.audit.attempts).toEqual([]);
    expect(engine.writeCalls).toEqual([]);
  });

  it('AC-4 input that breaks the contract is a 400 Problem and nothing runs', async () => {
    engine = createTestEngine({ actions: [subject()] });
${arm}    const answer = await engine.inject(${unexpected});

    expect(answer.statusCode).toBe(400);
    expect(answer.json()).toMatchObject({ code: 'VALIDATION_FAILED' });
    expect(engine.audit.attempts).toEqual([]);
  });

  it('AC-5 another method on the same path is 405', async () => {
    engine = createTestEngine({ actions: [subject()] });

    const answer = await engine.inject({
      method: ${quote(get ? 'DELETE' : 'GET')},
      path: ${quote(url)},
    });

    expect(answer.statusCode).toBe(405);
    expect(answer.headers.allow).toBe(${quote(http.method)});
  });
});
`;
}

