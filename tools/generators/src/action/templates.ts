// The text of the files the action generator writes. Everything is derived from the ActionModel,
// which has already been checked, and values are placed between quotes with `quote`. Prettier
// formats the result when the Writer flushes, so layout here only has to be readable.
import { quote } from '../shared/names.ts';
import type { ActionModel, PathParam } from './model.ts';

const connectionParam = (model: ActionModel): PathParam | undefined =>
  model.params.find((param) => param.schema === 'ConnectionIdSchema');

/** `{ cid: 'c1', qkey: '...' }`: a value for every path parameter. */
export function sampleInputText(model: ActionModel): string {
  const fields = model.params.map(
    (param) => `${param.name}: ${quote(param.sample)}`,
  );
  return `{ ${fields.join(', ')} }`;
}

// ---------------------------------------------------------------------------------------------
// The contract (libs/shared/contracts/src/registry/<stem>.ts)
// ---------------------------------------------------------------------------------------------

export function contractFile(model: ActionModel): string {
  const { camel, pascal } = model;
  const brands = [
    ...new Set(
      model.params
        .map((param) => param.schema)
        .filter((schema) => schema !== 'string'),
    ),
  ].sort();
  const field = (param: PathParam): string =>
    `${param.name}: ${param.schema === 'string' ? 'z.string().min(1)' : param.schema},`;
  const connection = connectionParam(model);
  const mcp =
    model.mcp === 'none'
      ? ''
      : `  mcp: {
    expose: true,
    mutating: ${String(model.mcp === 'mutating')},
    title: ${quote(model.summary)},
    description: ${quote(model.summary)},
  },
`;
  return `// ${model.id}: ${model.summary}
// Generated by \`pnpm nx g @app/generators:action ${model.id}\`. Describe the real input and
// output below, then run \`pnpm nx run contracts:api-docs\` so the committed API documents follow.
import { z } from 'zod';
${brands.length === 0 ? '' : `\nimport { ${brands.join(', ')} } from '../brands.ts';`}
import { defineAction } from '../kit/define-action.ts';

export const ${pascal}InputSchema = z.strictObject({
${model.params.map(field).join('\n')}
});

export const ${pascal}OutputSchema = z.strictObject({});

export const ${camel} = defineAction({
  id: ${quote(model.id)},
  kind: ${quote(model.kind)},
  summary: ${quote(model.summary)},
  input: ${pascal}InputSchema,
  output: ${pascal}OutputSchema,
  permission: ${quote(model.permission)},
  risk: ${quote(model.risk)},
  planning: ${quote(model.planning)},
  audit: ${quote(model.audit)},
  target: ${connection === undefined ? '() => ({})' : `(input) => ({ connectionId: input.${connection.name} })`},
${model.http === undefined ? '' : `  http: { method: ${quote(model.http.method)}, path: ${quote(model.http.path)} },\n`}${mcp}${model.cli === undefined ? '' : `  cli: { command: ${quote(model.cli)} },\n`}  since: ${quote(model.since)},
});
`;
}

// ---------------------------------------------------------------------------------------------
// The implementation (<module>/src/actions/<stem>.ts) and the fixture beside it
// ---------------------------------------------------------------------------------------------

export function actionFile(model: ActionModel): string {
  const { camel, pascal } = model;
  const planned = model.planned
    ? `    // Reads only: gates, warnings, consents and a preview. Write ports throw here (AC-2).
    plan: () => Promise.reject(notImplemented()),
    // The cheap re-check at execution time; answer { stale: '<what drifted>' } on drift.
    revalidate: () => Promise.reject(notImplemented()),
`
    : '';
  return `// ${model.id}: ${model.summary}
// Generated by \`pnpm nx g @app/generators:action ${model.id}\`. Every body below fails until you
// write it, and ${model.stem}.spec.ts fails with it. Follow docs/golden-path/ for the shape of a
// finished action: ports come in through the factory, errors are AppError, and execute() is the
// only place that may use ctx.writes (I-2).
import { ${camel} } from '@app/contracts';
import { AppError, implementAction, type ActionImpl } from '@app/kernel';

/**
 * The ports this action reads through: a subset of the module's deps (src/deps.ts), for example
 * \`Pick<${model.modulePascal}ModuleDeps, 'mgmt'>\`. The stub needs none.
 */
export type ${pascal}Deps = Readonly<Record<string, never>>;

const notImplemented = (): AppError =>
  new AppError('INTERNAL', {
    detail: ${quote(`${model.id} is not implemented yet.`)},
  });

/**
 * The module calls this with its ports (src/actions/index.ts). The stub takes no parameter so that
 * it compiles as it is; write \`(deps) => implementAction(...)\` when a body needs a port.
 */
export const create${pascal}Action: (
  deps: ${pascal}Deps,
) => ActionImpl<typeof ${camel}> = () =>
  implementAction(${camel}, {
${planned}    execute: () => Promise.reject(notImplemented()),
  });
`;
}

export function fixtureFile(model: ActionModel): string {
  return `// What ${model.stem}.spec.ts runs. Edit this file, not the spec, as the action grows.
import { create${model.modulePascal}FakeDeps } from '../testing';
import { create${model.pascal}Action } from './${model.stem}';

/** A valid input: one value for every required field of the contract. */
export const sampleInput = ${sampleInputText(model)};

/** The action under test, over the fakes of the module's ports (src/testing.ts). */
export function createSubject() {
  return create${model.pascal}Action(create${model.modulePascal}FakeDeps());
}
`;
}

// ---------------------------------------------------------------------------------------------
// The unit spec: what every action must do, whatever it does
// ---------------------------------------------------------------------------------------------

export function unitSpecFile(model: ActionModel): string {
  const job = model.kind === 'job';
  const outcomeKind = job ? 'job' : 'output';
  const purity = model.planned
    ? `
  it('AC-2 plan() reads only: every write port throws and none is called', async () => {
    expect(
      await checkPlanPurity([{ impl: subject(), input: sampleInput }]),
    ).toEqual([]);
  });
`
    : '';
  const audited = model.mutating
    ? `
  it('AC-4 a run leaves an audit attempt, then an outcome that names it, and a receipt', async () => {
    const engine = createTestExecutor();
    engine.executor.register(subject());

    const done = await runToEnd(engine);

    expect(done.kind).toBe(${quote(outcomeKind)});
    expect(engine.audit.attempts.map((row) => row.actionId)).toEqual([def.id]);
    expect(engine.audit.outcomes).toMatchObject([
      { actionId: def.id, result: 'ok', attemptSeq: 1 },
    ]);
    expect(engine.receipts.records).toMatchObject([
      { actionId: def.id, result: 'ok' },
    ]);
  });
`
    : `
  it('AC-4 a query leaves no audit row and no receipt, and answers in the shape of the contract', async () => {
    const engine = createTestExecutor();
    engine.executor.register(subject());

    const done = await runToEnd(engine);

    if (done.kind !== 'output') throw new Error(\`expected output, got \${done.kind}\`);
    expect(def.output.safeParse(done.output).success).toBe(true);
    expect(engine.audit.attempts).toEqual([]);
    expect(engine.receipts.records).toEqual([]);
  });
`;
  return `// Generated by \`pnpm nx g @app/generators:action ${model.id}\`. These tests state what every action
// must do; they fail until create${model.pascal}Action is implemented. Do not weaken them: fix the action,
// or add failure-path cases of your own. Rename the AC ids to those of your work package.
import { checkRegistry } from '@app/contracts';
import {
  ${model.planned ? 'checkPlanPurity,\n  ' : ''}createRoleAuthorizer,
  createTestContext,
  createTestExecutor,
  createTestPrincipal,
  denyAllAuthorizer,
  type TestExecutor,
} from '@app/kernel';
import { describe, expect, it } from 'vitest';

import { createSubject, sampleInput } from './${model.stem}.fixture';

const subject = createSubject;
const { def } = createSubject();
const KEY = 'generated-spec-key-0001';

/** Runs the action as the engine does: a plan first when one is required, then its execution. */
async function runToEnd(engine: TestExecutor) {
  const ctx = createTestContext({ idempotencyKey: KEY });
  const outcome = await engine.executor.run(def, sampleInput, ctx);
  if (outcome.kind !== 'planRequired') return outcome;
  return engine.executor.execute(
    {
      planId: outcome.plan.id,
      consents: [...outcome.plan.consentsRequired],
      confirmation: outcome.plan.confirmationPhrase,
      idempotencyKey: KEY,
    },
    ctx,
  );
}

describe(${quote(model.id)}, () => {
  it('AC-1 the contract passes the kit invariants and the sample input fits it', () => {
    expect(checkRegistry({ actions: [def], topics: [] })).toEqual([]);
    expect(def.input.safeParse(sampleInput).success).toBe(true);
  });
${purity}
  it('AC-3 a principal that does not hold ${model.permission} is refused before anything runs', async () => {
    const engine = createTestExecutor({
      executor: { authorizer: createRoleAuthorizer({ operator: [${quote(model.permission)}] }) },
    });
    engine.executor.register(subject());
    const ctx = createTestContext({
      principal: createTestPrincipal({ roles: ['intruder'] }),
      idempotencyKey: KEY,
    });

    await expect(
      engine.executor.run(def, sampleInput, ctx),
    ).rejects.toMatchObject({ code: 'FORBIDDEN_RBAC' });

    expect(engine.audit.attempts).toEqual([]);
    expect(engine.receipts.records).toEqual([]);
    expect(engine.writeCalls).toEqual([]);
  });

  it('AC-3 with no authorizer wired every call is refused: deny by default', async () => {
    const engine = createTestExecutor({
      executor: { authorizer: denyAllAuthorizer },
    });
    engine.executor.register(subject());

    await expect(
      runToEnd(engine),
    ).rejects.toMatchObject({ code: 'FORBIDDEN_RBAC' });

    expect(engine.audit.attempts).toEqual([]);
    expect(engine.writeCalls).toEqual([]);
  });

  it('AC-3 a principal that holds ${model.permission} is let through', async () => {
    const engine = createTestExecutor({
      executor: { authorizer: createRoleAuthorizer({ operator: [${quote(model.permission)}] }) },
    });
    engine.executor.register(subject());
    const ctx = createTestContext({
      principal: createTestPrincipal({ roles: ['operator'] }),
      idempotencyKey: KEY,
    });

    const outcome = await engine.executor.run(def, sampleInput, ctx);

    expect(['output', 'job', 'planRequired']).toContain(outcome.kind);
  });
${audited}});
`;
}

