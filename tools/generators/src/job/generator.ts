// A durable job (ADR-015): the definition in a service module, made with `defineJob` of the jobs
// library (@app/jobs, M0-31) and registered in `src/jobs/index.ts`, with a spec that fails until
// `run()` and `onDrain()` are written. The stub reaches no port: the write ports arrive only
// through the `JobContext` the runner builds. The action that starts a job is an action of kind `job`.
import { logger, type Tree } from '@nx/devkit';

import { assertId } from '../action/model.ts';
import { assertKebab, nameVariants, quote, stem } from '../shared/names.ts';
import { assertFree, requireService } from '../shared/service.ts';
import {
  appendImport,
  appendLine,
  appendToArray,
} from '../shared/source-edit.ts';
import { Writer } from '../shared/writer.ts';
import type { JobOptions } from './schema.ts';

/** The longest type defineJob accepts. */
const MAX_JOB_TYPE = 100;

interface JobModel {
  id: string;
  stem: string;
  pascal: string;
  camel: string;
  module: string;
  resumable: boolean;
}

function parseJob(options: JobOptions): JobModel {
  assertId(options.name, 'Job type');
  if (options.name.length > MAX_JOB_TYPE) {
    throw new Error(
      `Job type "${options.name}" is longer than ${String(MAX_JOB_TYPE)} characters.`,
    );
  }
  assertKebab(options.module, '--module');
  const names = nameVariants(options.name.replace(/\./g, '-'));
  return {
    id: options.name,
    stem: names.kebab,
    pascal: names.pascal,
    camel: names.camel,
    module: `svc-${stem(options.module, 'svc')}`,
    resumable: options.resumable ?? true,
  };
}

function jobFile(model: JobModel): string {
  const { camel, pascal } = model;
  return `// ${model.id}: a durable job. Generated by \`pnpm nx g @app/generators:job ${model.id}\`.
// run() and onDrain() fail until you write them, and ${model.stem}.spec.ts fails with them.
// run() yields progress and saves a checkpoint often enough to resume; onDrain() must park or flush
// everything the job holds before its deadline. A job changes the broker only through ports it is
// handed by the jobs library, never one it builds itself.
import { defineJob, type JobEvent } from '@app/jobs';
import { AppError } from '@app/kernel';
import { z } from 'zod';

export const ${pascal}InputSchema = z.strictObject({});
export const ${pascal}CheckpointSchema = z.strictObject({
  done: z.number().int().nonnegative(),
});
export const ${pascal}OutputSchema = z.strictObject({});
type ${pascal}Output = z.infer<typeof ${pascal}OutputSchema>;

const notImplemented = (): AppError =>
  new AppError('INTERNAL', { detail: ${quote(`the job ${model.id} is not implemented yet.`)} });

export const ${camel}Job = defineJob({
  type: ${quote(model.id)},
  version: 1,
  input: ${pascal}InputSchema,
  checkpoint: ${pascal}CheckpointSchema,
  output: ${pascal}OutputSchema,
  resumable: ${String(model.resumable)},
  run(): AsyncGenerator<JobEvent, ${pascal}Output, void> {
    throw notImplemented();
  },
  onDrain: () => Promise.reject(notImplemented()),
});
`;
}

function fixtureFile(model: JobModel): string {
  return `// What ${model.stem}.spec.ts runs. Edit this file, not the spec, as the job grows.

export const sampleInput = {};
export const sampleCheckpoint = { done: 0 };
`;
}

function specFile(model: JobModel): string {
  const { camel } = model;
  return `// Generated by \`pnpm nx g @app/generators:job ${model.id}\`. It fails until the job is
// implemented. Do not weaken it.
import type { JobId } from '@app/contracts';
import type { JobContext } from '@app/jobs';
import { createTestPrincipal, createWriteTrap } from '@app/kernel';
import { describe, expect, it } from 'vitest';

import { ${camel}Job as job } from './${model.stem}';
import { sampleCheckpoint, sampleInput } from './${model.stem}.fixture';

type Context = JobContext<
  ReturnType<typeof job.input.parse>,
  ReturnType<typeof job.checkpoint.parse>
>;

/** The context the runner builds, with write ports that throw: a body that writes in a spec is a bug. */
function context(signal: AbortSignal = new AbortController().signal): Context {
  const { writes } = createWriteTrap();
  return {
    jobId: 'job-1' as JobId,
    input: job.input.parse(sampleInput),
    principal: createTestPrincipal({ kind: 'job', surface: 'job', unattended: true }),
    signal,
    save: () => Promise.resolve(),
    journal: {
      append: () => Promise.resolve(),
      counts: () => Promise.resolve({ consumed: 0, published: 0, acked: 0, parked: 0 }),
      decideOnRedelivery: () => Promise.resolve('republish'),
    },
    throttle: { take: () => Promise.resolve() },
    leases: writes.connections,
    executorWrite: writes,
  };
}

describe(${quote(model.id)}, () => {
  it('AC-1 the definition is well formed and its samples fit its schemas', () => {
    expect(job.type).toBe(${quote(model.id)});
    expect(Number.isInteger(job.version) && job.version > 0).toBe(true);
    expect(job.input.safeParse(sampleInput).success).toBe(true);
    expect(job.checkpoint.safeParse(sampleCheckpoint).success).toBe(true);
    expect(job.resumable).toBe(${String(model.resumable)});
  });

  it('AC-2 run() reports progress and ends with an output that fits the schema', async () => {
    const events: string[] = [];
    const runner = job.run(context());
    let step = await runner.next();
    while (step.done !== true) {
      events.push(step.value.kind);
      step = await runner.next();
    }

    expect(job.output.safeParse(step.value).success).toBe(true);
    expect(events).toContain('progress');
  });

  it('AC-3 run() stops when its signal is aborted', async () => {
    const abort = new AbortController();
    const runner = job.run(context(abort.signal));
    abort.abort();
    let yielded = 0;
    let step = await runner.next();
    while (step.done !== true && yielded < 100) {
      yielded += 1;
      step = await runner.next();
    }

    expect(step.done).toBe(true);
  });

  it('AC-4 onDrain() finishes inside its deadline for every reason', async () => {
    for (const reason of ['cancel', 'shutdown', 'suspend', 'emergency'] as const) {
      const started = Date.now();
      await job.onDrain(context(), reason, 200);
      expect(Date.now() - started).toBeLessThan(200);
    }
  });
});
`;
}

export async function jobGenerator(
  tree: Tree,
  options: JobOptions,
): Promise<() => void> {
  const writer = new Writer(tree);
  const model = parseJob(options);
  const root = requireService(writer, model.module);
  const files = {
    job: `${root}/src/jobs/${model.stem}.ts`,
    fixture: `${root}/src/jobs/${model.stem}.fixture.ts`,
    spec: `${root}/src/jobs/${model.stem}.spec.ts`,
  };
  assertFree(writer, Object.values(files));
  const index = `${root}/src/jobs/index.ts`;
  const registry = writer.require(
    index,
    `Was ${model.module} made by the service-module generator?`,
  );
  if (registry.includes(`${model.camel}Job`)) {
    throw new Error(`${index} already registers ${model.camel}Job.`);
  }

  writer.write(files.job, jobFile(model));
  writer.write(files.fixture, fixtureFile(model));
  writer.write(files.spec, specFile(model));
  writer.write(
    index,
    appendToArray(
      appendImport(
        registry,
        index,
        `import { ${model.camel}Job } from './${model.stem}';`,
      ),
      index,
      'jobs',
      `${model.camel}Job`,
    ),
  );
  const barrel = `${root}/src/index.ts`;
  writer.write(
    barrel,
    appendLine(
      writer.require(
        barrel,
        `Was ${model.module} made by the service-module generator?`,
      ),
      `export { ${model.camel}Job } from './jobs/${model.stem}';`,
    ),
  );
  await writer.flush();

  return () => {
    logger.info(
      [
        `${model.id} is defined and registered; its tests fail until run() and onDrain() are written.`,
        `1. Describe the real input, checkpoint and output in ${files.job}.`,
        `2. Add an action of kind job that starts it: pnpm nx g @app/generators:action <ns.verb> --module=${model.module} --kind=job ...`,
        `3. pnpm nx run-many -t lint typecheck test -p ${model.module}`,
      ].join('\n'),
    );
  };
}

export default jobGenerator;
