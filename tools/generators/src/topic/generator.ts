// A live topic (ADR-005), declared once in the contract registry: the contract with a bounded
// ring (I-6), the registrations, and a spec that holds the topic to the kit invariants and the live
// frames. The provider that feeds the topic arrives with the live hub (M0-33); nothing here
// subscribes, publishes or opens a socket.
import { logger, type Tree } from '@nx/devkit';

import { assertId, assertPermission } from '../action/model.ts';
import { assertKebab, nameVariants, quote, stem } from '../shared/names.ts';
import {
  CONTRACTS_INDEX,
  REGISTRY_DIR,
  REGISTRY_INDEX,
  assertFree,
  assertIdFree,
  requireService,
} from '../shared/service.ts';
import {
  appendImport,
  appendLine,
  appendToArray,
  appendToPropertyArray,
} from '../shared/source-edit.ts';
import { Writer } from '../shared/writer.ts';
import type { TopicOptions } from './schema.ts';

const FLOWS = ['credit', 'snapshot-delta'] as const;
const QOS = ['lossless', 'latest', 'sampled'] as const;
export const DEFAULT_RING_ITEMS = 1000;
export const DEFAULT_RING_BYTES = 1024 * 1024;

export interface TopicModel {
  readonly id: string;
  readonly stem: string;
  readonly pascal: string;
  readonly camel: string;
  readonly module: string;
  readonly modulePascal: string;
  readonly flow: (typeof FLOWS)[number];
  readonly qos: (typeof QOS)[number];
  readonly permission: string;
  readonly maxHz: number | undefined;
  readonly ringItems: number;
  readonly ringBytes: number;
}

function positive(
  value: number | string | undefined,
  option: string,
): number | undefined {
  if (value === undefined) return undefined;
  const number = Number(value);
  if (!(number > 0) || !Number.isFinite(number)) {
    throw new Error(
      `--${option} must be a positive number; got "${String(value)}".`,
    );
  }
  return number;
}

function integer(
  value: number | string | undefined,
  option: string,
  fallback: number,
): number {
  const number = positive(value, option) ?? fallback;
  if (!Number.isSafeInteger(number)) {
    throw new Error(
      `--${option} must be a whole number; got "${String(value)}".`,
    );
  }
  return number;
}

export function parseTopic(options: TopicOptions): TopicModel {
  assertId(options.name, 'Topic id');
  assertKebab(options.module, '--module');
  const flow = FLOWS.find((candidate) => candidate === options.flow);
  if (flow === undefined)
    throw new Error(`--flow must be one of ${FLOWS.join(', ')}.`);
  const qos = QOS.find((candidate) => candidate === options.qos);
  if (qos === undefined)
    throw new Error(`--qos must be one of ${QOS.join(', ')}.`);
  if (qos === 'sampled' && flow !== 'credit') {
    throw new Error(
      'qos sampled keeps every n-th item of a stream: it needs --flow=credit.',
    );
  }
  const maxHz = positive(options.maxHz, 'max-hz');
  if (qos === 'latest' && maxHz === undefined) {
    throw new Error('qos latest coalesces at a rate: pass --max-hz.');
  }
  const module = `svc-${stem(options.module, 'svc')}`;
  const names = nameVariants(options.name.replace(/\./g, '-'));
  return {
    id: options.name,
    stem: `${names.kebab}-topic`,
    pascal: names.pascal,
    camel: names.camel,
    module,
    modulePascal: nameVariants(module.slice('svc-'.length)).pascal,
    flow,
    qos,
    permission: assertPermission(options.permission),
    maxHz,
    ringItems: integer(options.ringItems, 'ring-items', DEFAULT_RING_ITEMS),
    ringBytes: integer(options.ringBytes, 'ring-bytes', DEFAULT_RING_BYTES),
  };
}

function contractFile(model: TopicModel): string {
  const { camel, pascal } = model;
  return `// ${model.id}: a live topic (${model.flow}, ${model.qos}).
// Generated by \`pnpm nx g @app/generators:topic ${model.id}\`. Describe the real params and item
// below, then run \`pnpm nx run contracts:api-docs\` so the AsyncAPI document follows. An item
// never carries a write-only secret, and the ring is bounded by items and bytes (I-6).
import { z } from 'zod';

import { defineTopic } from '../kit/define-topic.ts';

export const ${pascal}ParamsSchema = z.strictObject({});

export const ${pascal}ItemSchema = z.strictObject({
  id: z.string().min(1),
});

export const ${camel}Topic = defineTopic({
  id: ${quote(model.id)},
  params: ${pascal}ParamsSchema,
  item: ${pascal}ItemSchema,
  qos: ${quote(model.qos)},
  flow: ${quote(model.flow)},
  permission: ${quote(model.permission)},
  key: (item) => item.id,
${model.maxHz === undefined ? '' : `  maxHz: ${String(model.maxHz)},\n`}  ring: { items: ${String(model.ringItems)}, bytes: ${String(model.ringBytes)} },
});
`;
}

function fixtureFile(model: TopicModel): string {
  return `// What topics.${model.stem}.spec.ts checks. Edit this file, not the spec, as the topic grows.

/** Params that pass the topic's params schema. */
export const sampleParams = {};

/** An item that passes the topic's item schema. */
export const sampleItem = { id: 'item-1' };
`;
}

function specFile(model: TopicModel): string {
  const { camel } = model;
  const frames =
    model.flow === 'credit'
      ? `    expect(
      ServerFrameSchema.safeParse({
        t: 'data',
        sid: 1,
        seq: 1,
        items: [item],${model.qos === 'sampled' ? '\n        sampledEvery: 2,' : ''}
      }).success,
    ).toBe(true);`
      : `    expect(
      ServerFrameSchema.safeParse({ t: 'snapshot', sid: 1, seq: 1, items: [item] }).success,
    ).toBe(true);
    expect(
      ServerFrameSchema.safeParse({
        t: 'delta',
        sid: 1,
        seq: 2,
        upserts: [item],
        removes: [topic.key?.(item) ?? ''],
      }).success,
    ).toBe(true);`;
  return `// Generated by \`pnpm nx g @app/generators:topic ${model.id}\`. It holds the topic to the kit
// invariants and to the live frames it travels in. Do not weaken it.
import {
  ClientFrameSchema,
  ServerFrameSchema,
  checkRegistry,
  ${camel}Topic,
} from '@app/contracts';
import { describe, expect, it } from 'vitest';

import { create${model.modulePascal}Module } from './module';
import { create${model.modulePascal}FakeDeps } from './testing';
import { sampleItem, sampleParams } from './topics.${model.stem}.fixture';

const topic = ${camel}Topic;

describe(${quote(model.id)}, () => {
  it('AC-1 the contract passes the kit invariants: bounded ring, keyed, no secret', () => {
    expect(checkRegistry({ actions: [], topics: [topic] })).toEqual([]);
    // Bounded by items and by bytes (I-6): whatever the numbers are, both are finite.
    expect(Number.isSafeInteger(topic.ring.items) && topic.ring.items > 0).toBe(
      true,
    );
    expect(Number.isSafeInteger(topic.ring.bytes) && topic.ring.bytes > 0).toBe(
      true,
    );
  });

  it('AC-2 the sample params and item fit the schemas, and travel in live frames', () => {
    const item = topic.item.parse(sampleItem);

    expect(topic.params.safeParse(sampleParams).success).toBe(true);
    expect(
      ClientFrameSchema.safeParse({
        t: 'sub',
        sid: 1,
        topic: topic.id,
        params: sampleParams,
        credit: 16,
      }).success,
    ).toBe(true);
${frames}
  });

  it('AC-3 an item has one stable key, so coalescing and removals agree', () => {
    const first = topic.key?.(topic.item.parse(sampleItem));
    const second = topic.key?.(topic.item.parse({ ...sampleItem }));

    expect(typeof first).toBe('string');
    expect(first).toBe(second);
  });

  it('AC-4 the module declares the topic', () => {
    expect(
      create${model.modulePascal}Module(create${model.modulePascal}FakeDeps()).topics,
    ).toContain(topic);
  });

  it.todo('AC-5 a provider feeds the topic: wired through the live hub (M0-33)');
});
`;
}

export async function topicGenerator(
  tree: Tree,
  options: TopicOptions,
): Promise<() => void> {
  const writer = new Writer(tree);
  const model = parseTopic(options);
  const root = requireService(writer, model.module);
  assertIdFree(writer, model.id, 'topic');

  const contract = `${REGISTRY_DIR}/${model.stem}.ts`;
  const fixture = `${root}/src/topics.${model.stem}.fixture.ts`;
  const spec = `${root}/src/topics.${model.stem}.spec.ts`;
  assertFree(writer, [contract, fixture, spec]);

  writer.write(contract, contractFile(model));
  writer.write(fixture, fixtureFile(model));
  writer.write(spec, specFile(model));

  const { camel, stem: file } = model;
  const registered = (
    path: string,
    hint: string,
    change: (text: string) => string,
  ): void => {
    writer.write(path, change(writer.require(path, hint)));
  };
  registered(REGISTRY_INDEX, 'The contract registry must exist.', (text) =>
    appendToPropertyArray(
      appendImport(
        text,
        REGISTRY_INDEX,
        `import { ${camel}Topic } from './${file}.ts';`,
      ),
      REGISTRY_INDEX,
      'registry',
      'topics',
      `${camel}Topic`,
    ),
  );
  registered(CONTRACTS_INDEX, 'The contracts index must exist.', (text) =>
    appendLine(text, `export * from './registry/${file}.ts';`),
  );
  const topics = `${root}/src/topics.ts`;
  registered(
    topics,
    `Was ${model.module} made by the service-module generator?`,
    (text) =>
      appendToArray(
        appendImport(
          text,
          topics,
          `import { ${camel}Topic } from '@app/contracts';`,
        ),
        topics,
        'topics',
        `${camel}Topic`,
      ),
  );
  await writer.flush();

  return () => {
    logger.info(
      [
        `${model.id} is declared and registered.`,
        `1. Describe the real params and item in ${contract}, and update ${fixture}.`,
        `2. pnpm nx run contracts:api-docs`,
        `3. pnpm nx run-many -t lint typecheck test -p ${model.module},contracts`,
        `4. pnpm nx run contracts:api-docs-check`,
        'The provider that feeds the topic is wired through the live hub (M0-33).',
      ].join('\n'),
    );
  };
}

export default topicGenerator;
